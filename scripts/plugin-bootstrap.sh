#!/usr/bin/env bash
# plugin-bootstrap.sh — SessionStart hook of the limit-alerts plugin.
#
# Three of this project's four surfaces run inside plugin context and can just
# use ${CLAUDE_PLUGIN_ROOT}. The statusline command and the launchd job cannot:
# they start outside Claude Code, receive no CLAUDE_PLUGIN_* variables, and a
# path into the plugin cache dies on the next update, because that cache is
# version-stamped (~/.claude/plugins/cache/<marketplace>/<plugin>/<version>/).
#
# So this script mirrors the two scripts those surfaces need into the
# update-stable data directory and generates wrappers there that carry the
# environment. It then applies the opt-in statusline and launchd settings.
#
# Every step is best-effort: a broken step prints a systemMessage and the hook
# still exits 0. A session must never fail because of this project.

set -euo pipefail

DATA="${UM_STATE_DIR:-${CLAUDE_PLUGIN_DATA:-}}"
ROOT="${CLAUDE_PLUGIN_ROOT:-}"
[ -n "$DATA" ] && [ -n "$ROOT" ] || exit 0
[ -d "$ROOT/scripts" ] || exit 0

BIN="$DATA/bin"
MESSAGES=()

note() { MESSAGES+=("$1"); }

# Everything this hook has to say is emitted once, from the EXIT trap, so no
# step has to care about being the last one. Silence is the normal outcome.
emit() {
  [ ${#MESSAGES[@]} -gt 0 ] || exit 0
  local text="" m jq_bin
  for m in "${MESSAGES[@]}"; do
    [ -n "$text" ] && text="$text"$'\n'
    text="$text$m"
  done
  jq_bin="$(command -v jq || echo /opt/homebrew/bin/jq)"
  if [ -x "$jq_bin" ]; then
    "$jq_bin" -n --arg t "$text" '{systemMessage: $t}'
  fi
  exit 0
}
trap emit EXIT

LANG_UM="${UM_LANG:-${CLAUDE_PLUGIN_OPTION_LANG:-ru}}"

# ---------------------------------------------------------------- mirroring

# $1 = wrapper path, $2 = target script. The wrapper is what makes an
# out-of-plugin process behave like an in-plugin one: it is the only place
# that knows both the data directory and the resolved options.
write_wrapper() {
  local path="$1" target="$2"
  cat > "$path" <<EOF
#!/usr/bin/env bash
# Generated by plugin-bootstrap.sh — do not edit, regenerated on every version
# change of the limit-alerts plugin.
export UM_STATE_DIR="$DATA"
export UM_LANG="$LANG_UM"
exec bash "$target" "\$@"
EOF
  chmod +x "$path"
}

mirror() {
  local repo_version installed_version
  repo_version=$(cat "$ROOT/VERSION" 2>/dev/null || echo "unknown")
  installed_version=$(cat "$BIN/.version" 2>/dev/null || echo "")
  [ "$repo_version" = "$installed_version" ] && return 0

  mkdir -p "$BIN" || return 1
  cp "$ROOT/scripts/usage-monitor.sh" "$BIN/usage-monitor.sh" || return 1
  cp "$ROOT/scripts/statusline-with-limits.sh" "$BIN/statusline-with-limits.sh" || return 1
  chmod +x "$BIN/usage-monitor.sh" "$BIN/statusline-with-limits.sh" || return 1

  # notify-attention.sh and compact-advisor.sh are deliberately not mirrored:
  # they only ever run from hooks, where ${CLAUDE_PLUGIN_ROOT} is already
  # correct and a mirrored copy would just be a second thing to keep in sync.

  write_wrapper "$BIN/cron.sh"       "$BIN/usage-monitor.sh"          || return 1
  write_wrapper "$BIN/statusline.sh" "$BIN/statusline-with-limits.sh" || return 1

  printf '%s\n' "$repo_version" > "$BIN/.version" || return 1
  return 0
}

if ! mirror; then
  if [ "$LANG_UM" = "en" ]; then
    note "limit-alerts: could not prepare $BIN — statusline and background agent are unavailable."
  else
    note "limit-alerts: не удалось подготовить $BIN — статусная строка и фоновый агент недоступны."
  fi
fi
